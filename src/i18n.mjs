const index = new Map(messages.map(([es, ca, en]) => [es, { es, ca, en }]));
const ordered = [...messages].sort((a, b) => b[0].length - a[0].length);
export function translate(locale, value) { return index.get(value)?.[locale] ?? value; }

// Short fragments also cover console strings with inserted paths, counts, or commands.
export function translateOutput(locale, value) {
  if (locale === "es" || !value) return value;
  return ordered
    .reduce((result, row) => result.replaceAll(row[0], row[locale === "ca" ? 1 : 2]), value);
}

export function localizeMarkup(markup, locale) {
  if (locale === "es") return markup;
  const localizeFragment = fragment => fragment
    .replace(/>([^<>]+)</g, (match, inner) => {
      const trimmed = inner.trim();
      return trimmed ? `>${inner.replace(trimmed, translate(locale, trimmed))}<` : match;
    })
    .replace(/\b(aria-label|aria-description|title|content)="([^"]*)"/g,
      (match, name, value) => `${name}="${translate(locale, value).replaceAll('"', '&quot;')}"`);
  return markup.split(/(<(?:style|script)\b[^>]*>[\s\S]*?<\/(?:style|script)>)/gi)
    .map(part => /^<(?:style|script)\b/i.test(part) ? part : localizeFragment(part)).join("");
}
